#!/usr/bin/env node
/**
 * Quick prompt editor for the tavern-stages plugin.
 *
 * `src/prompts.json` is the single editable source for all model-facing
 * prompt copy. The `prebuild`/`pretest` npm scripts auto-regenerate
 * `src/prompts.defaults.ts` from it (see `scripts/sync-prompts.mjs`); this
 * editor wraps the same regeneration after a `set`.
 *
 * The sibling `@ai4rpg/dsh-stage-switch` checkout has its own
 * `scripts/sync-prompts.mjs` for its `prompts.defaults.ts` (no cross-repo
 * coupling).
 *
 * Usage:
 *   node scripts/prompts.mjs                     list every prompt
 *   node scripts/prompts.mjs list                same
 *   node scripts/prompts.mjs show <key>          print one prompt's full text
 *   node scripts/prompts.mjs set <key> <text>    edit one prompt and re-sync the defaults
 *   node scripts/prompts.mjs sync                re-regenerate the defaults from prompts.json (no edit)
 *   node scripts/prompts.mjs --help               this help
 *
 * Keys are dot paths into prompts.json, e.g. `stages.route`, `section`,
 * `uiComplete`, `forgeTool.description`, `commands.tavernForge`.
 *
 * `src/prompts.defaults.ts` is auto-regenerated by `prebuild`/`pretest`, so
 * after `set` you only need `npm run build` (which runs prebuild) for the
 * built `lib/` to pick up the embedded fallback; `node scripts/prompts.mjs
 * sync` re-runs the regeneration without touching the JSON.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import {
  promptsJsonPath,
  readPrompts,
  syncAll,
  repoRoot,
} from './sync-prompts.mjs'

const USAGE = `Usage:
  node scripts/prompts.mjs [list]               list every tavern-stages prompt key
  node scripts/prompts.mjs show <key>           print one prompt's full text
  node scripts/prompts.mjs set <key> <text>     edit one prompt and re-sync the defaults
  node scripts/prompts.mjs sync                 re-regenerate the defaults from prompts.json (no edit)
  node scripts/prompts.mjs --help               this help`

/** Deep-set a value at a dot path inside a plain object (returns the new value). */
function setAt(target, key, value) {
  const parts = key.split('.')
  let node = target
  for (const part of parts.slice(0, -1)) {
    const next = node[part]
    if (typeof next !== 'object' || next === null) {
      throw new Error(`unknown prompt key "${key}" (segment "${part}" is not an object)`)
    }
    node = next
  }
  const last = parts[parts.length - 1]
  if (!(last in node) || typeof node[last] !== 'string') {
    throw new Error(`unknown prompt key "${key}"`)
  }
  node[last] = value
  return value
}

/** Read a value at a dot path (throws on unknown keys). */
function getAt(target, key) {
  const parts = key.split('.')
  let node = target
  for (const part of parts) {
    if (typeof node !== 'object' || node === null || !(part in node)) {
      throw new Error(`unknown prompt key "${key}"`)
    }
    node = node[part]
  }
  if (typeof node !== 'string') throw new Error(`prompt key "${key}" is not a string`)
  return node
}

/** All dot-path keys of a plain object, in order. */
function keysOf(node, prefix = '') {
  const out = []
  for (const [key, value] of Object.entries(node)) {
    const at = prefix === '' ? key : `${prefix}.${key}`
    if (typeof value === 'object' && value !== null && !Array.isArray(value)) {
      out.push(...keysOf(value, at))
    } else {
      out.push(at)
    }
  }
  return out
}

function main() {
  const [command, ...rest] = process.argv.slice(2)
  if (command === '--help' || command === '-h') {
    console.log(USAGE)
    return
  }
  const prompts = readPrompts(repoRoot)
  if (command === undefined || command === 'list') {
    console.log(`Prompt source: ${promptsJsonPath(repoRoot)}\n`)
    for (const key of keysOf(prompts)) {
      const text = getAt(prompts, key)
      const preview = text.length > 64 ? `${text.slice(0, 64)}…` : text
      console.log(`  ${key}\n      ${preview.replace(/\n/g, ' ')}\n`)
    }
    console.log('Set one with: node scripts/prompts.mjs set <key> <text>')
    return
  }
  if (command === 'show') {
    const key = rest[0]
    if (key === undefined) throw new Error('usage: prompts.mjs show <key>')
    console.log(getAt(prompts, key))
    return
  }
  if (command === 'set') {
    const [key, ...textParts] = rest
    if (key === undefined || textParts.length === 0) {
      throw new Error('usage: prompts.mjs set <key> <text>')
    }
    const text = textParts.join(' ')
    setAt(prompts, key, text)
    writeFileSync(promptsJsonPath(repoRoot), `${JSON.stringify(prompts, null, 2)}\n`)
    console.log(`✓ ${key} updated in ${promptsJsonPath(repoRoot)}\n`)
    syncAll(repoRoot)
    console.log('\nNext: npm run build (runs prebuild → sync-prompts.mjs for defaults.ts)')
    return
  }
  if (command === 'sync') {
    syncAll(repoRoot)
    console.log('\nNext: npm run build (runs prebuild → sync-prompts.mjs for defaults.ts)')
    return
  }
  console.error(USAGE)
  process.exitCode = 1
}

try {
  main()
} catch (error) {
  console.error(`prompts.mjs: ${error instanceof Error ? error.message : String(error)}`)
  process.exitCode = 1
}
