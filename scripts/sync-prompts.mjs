#!/usr/bin/env node
/**
 * Prompt-sync helper for the `prebuild`/`pretest` npm scripts.
 *
 * `src/prompts.json` is the single editable source for tavern-stages
 * model-facing copy. This helper regenerates the one derived artifact:
 *
 *  `src/prompts.defaults.ts` — the embedded fallback shipped in `lib/`
 *  (keeps stale installs working until the JSON reaches them).
 *
 * The sibling `@ai4rpg/dsh-stage-switch` checkout has its own
 * `scripts/sync-prompts.mjs` for its `prompts.defaults.ts` (no cross-repo
 * coupling).
 *
 * @module scripts/sync-prompts
 */

import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

export const repoRoot = fileURLToPath(new URL('..', import.meta.url))

/** Absolute path of the single prompt source. */
export function promptsJsonPath(root = repoRoot) {
  return path.join(root, 'src', 'prompts.json')
}

/** Read the prompt source as a plain JS object. */
export function readPrompts(root = repoRoot) {
  return JSON.parse(readFileSync(promptsJsonPath(root), 'utf8'))
}

/**
 * Regenerate `src/prompts.defaults.ts` from `src/prompts.json`. The file is a
 * typed TS module whose default object is the JSON literal itself (a JSON
 * document is valid TypeScript), so the two stay meaning-identical by
 * construction after every sync.
 */
export function writeDefaultsTs(root = repoRoot, prompts = readPrompts(root)) {
  const file = path.join(root, 'src', 'prompts.defaults.ts')
  const json = JSON.stringify(prompts, null, 2)
  const body = `/**
 * Embedded fallback copy of \`src/prompts.json\` plus its type.
 *
 * GENERATED by \`scripts/sync-prompts.mjs\` (run automatically by the \`prebuild\`
 * and \`pretest\` npm scripts) — do not hand-edit the prompt strings here;
 * edit \`src/prompts.json\` (or run \`node scripts/prompts.mjs set <key> <text>\`),
 * then re-sync. The built \`lib/\` keeps working even when the JSON is absent
 * from a stale install; \`tests/prompts.spec.ts\` pins the loaded overlay to
 * this copy so the two cannot drift silently.
 *
 * @module @ai4rpg/dsh-tavern-stages/prompts.defaults
 */

/** All model-facing prompt copy owned by @ai4rpg/dsh-tavern-stages. */
export interface TavernPrompts {
  /** One stage instruction per stage name (the \`stage:context\` text). */
  readonly stages: Record<'route' | 'design' | 'planning' | 'content' | 'ui', string>
  /** The \`stage:policy\` switch-guidance text rendered while a stage is eligible. */
  readonly section: string
  /** The \`tavern-cards/ui-complete\` guidance rendered in the ui stage when done. */
  readonly uiComplete: string
  /** Path block appended to a named subagent's first prompt: the resolved
   * absolute directories of the tavern skills that agent body references, so
   * the child can read its \`references/\` docs without a \`skill\` lookup. */
  readonly subagentSkillDirs: {
    readonly heading: string
    readonly line: string
    readonly note: string
  }
  /** Model-facing \`tavern_forge\` tool copy. */
  readonly forgeTool: {
    readonly description: string
    readonly command: string
    readonly args: string
  }
  /** Human slash-command descriptions. */
  readonly commands: {
    readonly tavernForge: string
    readonly tavernPack: string
  }
}

/** The fallback copy of \`src/prompts.json\`; regenerated by the sync script. */
export const DEFAULT_TAVERN_PROMPTS = ${json} as const satisfies TavernPrompts
`
  writeFileSync(file, body)
  console.log('  ✓ src/prompts.defaults.ts regenerated from src/prompts.json')
}

/** Sync every prompt-derived artifact from `src/prompts.json`. */
export function syncAll(root = repoRoot) {
  writeDefaultsTs(root, readPrompts(root))
}

if (import.meta.url === `file://${process.argv[1]}`) {
  syncAll()
}
